/** Authored ASCII, in a common 23 x 15 frame. No raster icons or rarity recolouring. */
export type ItemInk = 'bone' | 'steel' | 'rust' | 'leather' | 'wood' | 'leaf' | 'silk' | 'venom' | 'fire' | 'ice' | 'arcane' | 'gold'
export interface ItemSprite { lines: string[]; ink: ItemInk; text: string }
function sprite(ink: ItemInk, art: string): ItemSprite {
  const rows = art.replace(/^\n|\n$/g, '').split('\n').map((row) => row.trimEnd())
  const indent = Math.min(...rows.filter((row) => row.trim()).map((row) => row.search(/\S/)))
  const trimmed = rows.map((row) => row.slice(indent))
  const width = Math.max(...trimmed.map((row) => row.length))
  const left = ' '.repeat(Math.max(0, Math.floor((23 - width) / 2)))
  const lines = trimmed.map((row) => (left + row).padEnd(23))
  while (lines.length < 15) { lines.push(' '.repeat(23)); if (lines.length < 15) lines.unshift(' '.repeat(23)) }
  return { ink, lines, text: lines.join('\n') }
}

