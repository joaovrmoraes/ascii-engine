export function itemGlyphTone(glyph: string): 'edge' | 'body' | 'shade' | 'accent' {
  if ('+*@'.includes(glyph)) return 'accent'
  if (':;.,'.includes(glyph)) return 'shade'
  if ('#=ox'.includes(glyph)) return 'body'
  return 'edge'
}
